import json, os, subprocess, requests
from datetime import datetime

GITHUB_TOKEN = os.environ["GH_PAT"]
REPO = os.environ["GITHUB_REPOSITORY"]
BASE_BRANCH = "main"

def git(cmd, cwd=None):
    subprocess.run(cmd, shell=True, check=True, cwd=cwd)

def create_pr(branch, title, body):
    resp = requests.post(
        f"https://api.github.com/repos/{REPO}/pulls",
        json={"title": title, "body": body, "head": branch, "base": BASE_BRANCH},
        headers={
            "Authorization": f"Bearer {GITHUB_TOKEN}",
            "Accept": "application/vnd.github+json",
        }
    )
    resp.raise_for_status()
    return resp.json()["html_url"]

if __name__ == "__main__":
    with open("fix_summary.json") as f:
        summary = json.load(f)

    applied = summary["applied"]
    if not applied:
        print("Nothing to commit.")
        exit(0)

    # Le repo cloné est dans target-app/
    app_dir = "target-app"
    if not os.path.exists(app_dir):
        app_dir = "."  # fallback si scan local

    branch = f"fix/trivy-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    cves = ", ".join(set(f["cve"] for f in applied))

    git(f'git config user.email "security-bot@ci"', cwd=app_dir)
    git(f'git config user.name "Security Bot"', cwd=app_dir)
    git(f"git checkout -b {branch}", cwd=app_dir)

    # Ajouter uniquement les fichiers de dépendances modifiés
    for f in ["package.json", "package-lock.json", "yarn.lock", "requirements.txt"]:
        if os.path.exists(os.path.join(app_dir, f)):
            git(f"git add {f}", cwd=app_dir)

    # Vérifier qu'il y a quelque chose à commiter
    result = subprocess.run("git diff --cached --name-only", shell=True, capture_output=True, text=True, cwd=app_dir)
    if not result.stdout.strip():
        print("No changes to commit.")
        exit(0)

    git(f'git commit -m "fix(security): auto-fix {len(applied)} Trivy vulnerabilities\n\nCVEs: {cves}"', cwd=app_dir)

    # Push avec le token
    repo_url = os.environ.get("REPO_URL", "")
    if repo_url:
        # Injecter le token dans l'URL pour pouvoir pusher
        auth_url = repo_url.replace("https://", f"https://x-access-token:{GITHUB_TOKEN}@")
        git(f"git remote set-url origin {auth_url}", cwd=app_dir)

    git(f"git push origin {branch}", cwd=app_dir)

    # Extraire owner/repo depuis l'URL du repo externe
    import re
    remote = subprocess.run("git remote get-url origin", shell=True, capture_output=True, text=True, cwd=app_dir)
    match = re.search(r"github\.com[:/](.+/.+?)(?:\.git)?$", remote.stdout.strip())
    target_repo = match.group(1) if match else REPO

    resp = requests.post(
        f"https://api.github.com/repos/{target_repo}/pulls",
        json={"title": f"fix(security): auto-fix {len(applied)} vulnerabilities [{cves}]",
              "body": "\n".join([
                  "## 🤖 Automated Security Fix\n",
                  "Generated by Groq AI from Trivy scan.\n",
                  *[f"- **{f['pkg']}** — {f['cve']}: `{f['cmd']}`" for f in applied]
              ]),
              "head": branch,
              "base": BASE_BRANCH},
        headers={
            "Authorization": f"Bearer {GITHUB_TOKEN}",
            "Accept": "application/vnd.github+json",
        }
    )
    resp.raise_for_status()
    pr_url = resp.json()["html_url"]
    print(f"✅ PR created: {pr_url}")
